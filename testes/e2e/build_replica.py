import json,sys
d=json.load(open('/home/claude/diag/schema.json'))
UD={('auditorias','prioridade'):'os_prioridade',('equipamentos','status'):'equipamento_status',('equipamentos','criticidade'):'os_prioridade',
('logs_sistema','role'):'app_role',('ordens_servico','tipo'):'os_tipo',('ordens_servico','status'):'os_status',('ordens_servico','prioridade'):'os_prioridade',
('os_historico','status_anterior'):'os_status',('os_historico','status_novo'):'os_status',('perfis','role'):'app_role',('preventivas_agendamentos','status'):'preventiva_status'}
out=[]
out.append("""
create extension if not exists "uuid-ossp";
do $$ begin create role anon nologin; exception when others then null; end $$;
do $$ begin create role authenticated nologin; exception when others then null; end $$;
create schema if not exists auth;
create or replace function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.uid', true),'')::uuid $$;
create table if not exists auth.users(id uuid primary key);
create schema if not exists storage;
create table storage.buckets(id text primary key, name text, public boolean default false);
create table storage.objects(id uuid primary key default gen_random_uuid(), bucket_id text, name text, owner uuid);
create or replace function storage.foldername(name text) returns text[] language sql immutable as $$ select (string_to_array(name,'/'))[1:array_length(string_to_array(name,'/'),1)-1] $$;
alter table storage.objects enable row level security;
grant usage on schema public, auth, storage to anon, authenticated;
create sequence if not exists public.equipamento_tag_global_seq;
""")
for e in d['enums']:
    out.append(f"create type public.{e['tipo']} as enum ({', '.join(repr(v) for v in e['valores'])});")
for t in d['tabelas']:
    cols=[]
    for c in t['colunas']:
        typ=c['tipo']
        if typ=='USER-DEFINED': typ=UD[(t['tabela'],c['coluna'])]
        if t['tabela']=='ordens_servico' and c['coluna']=='numero':
            cols.append('numero bigint generated by default as identity'); continue
        s=f"{c['coluna']} {typ}"
        if c['padrao']: s+=f" default {c['padrao']}"
        if c['nulo']=='NO': s+=" not null"
        cols.append(s)
    out.append(f"create table public.{t['tabela']} ({', '.join(cols)});")
cons=sorted(d['restricoes'],key=lambda c:(0 if c['definicao'].startswith(('PRIMARY','UNIQUE')) else 1))
for c in cons:
    out.append(f"alter table {c['tabela']} add constraint {c['nome']} {c['definicao']};")
for f in d['funcoes']:
    out.append(f['definicao'].replace('\r','')+';')
for v in d['views']:
    out.append(f"create view public.{v['nome']} as {v['definicao']}")
for t in d['triggers']: out.append(t['definicao']+';')
for r in d['rls_ativo']:
    if r['rls']: out.append(f"alter table public.{r['tabela']} enable row level security;")
for p in d['politicas_rls']:
    roles=', '.join(p['perfis'])
    s=f"create policy \"{p['nome']}\" on {p['schema']}.{p['tabela']} as permissive for {p['comando']} to {roles}"
    if p['using']: s+=f" using ({p['using']})"
    if p['with_check']: s+=f" with check ({p['with_check']})"
    out.append(s+';')
for b in d['buckets_storage']:
    out.append(f"insert into storage.buckets(id,name,public) values ('{b['id']}','{b['id']}',{str(b['publico']).lower()});")
out.append("grant select,insert,update,delete on all tables in schema public to anon, authenticated; grant usage,select on all sequences in schema public to anon, authenticated; grant select,insert,update,delete on storage.objects, storage.buckets to anon, authenticated;")
open('replica.sql','w').write('\n'.join(out))
